#!/usr/bin/env python3
"""Backfill ``retrieval_recall`` into runs produced BEFORE the field existed.

The summary fields are only written by the runner at export time, so every
``results.json`` created before SPEC §5.8 has no ``retrieval_recall``. The
per-turn evidence is still there (``turn_results[*].assertion_details`` carries
``rule_type`` + ``passed``), so the metric can be recomputed exactly — the only
extra input is the *declared* denominator, read from the scenario YAML (D1).

This script patches, per run directory:

* ``results.json`` — the six recall fields added to every run summary, every
  other key left untouched;
* ``summary.csv`` — rewritten from the patched summaries using the same column
  set/order as ``BenchmarkRunner._export_results`` (the six columns are
  inserted after ``pass_rate``);
* ``retrieval_recall_backfill.json`` — provenance: timestamp, dataset root,
  declared counts used, and which runs have denominator drift (the scenario
  gained pins after the run, so their figure is a lower bound).

Originals are copied to ``*.bak`` once (never overwritten afterwards), and
``--dry-run`` reports without writing. ``summary.md`` is a preview artifact and
is intentionally left alone — it is regenerated by the next real run.

Usage::

    python scripts/backfill_retrieval_recall.py --dry-run
    python scripts/backfill_retrieval_recall.py
    python scripts/backfill_retrieval_recall.py --results outputs/runs/20261106_150300
"""

from __future__ import annotations

import argparse
import csv
import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:  # allow `python scripts/backfill_retrieval_recall.py`
    sys.path.insert(0, str(REPO_ROOT))

from core.metrics import recall_with_ci  # noqa: E402
from scripts.retrieval_recall import (  # noqa: E402
    DEFAULT_DATASET,
    DEFAULT_RESULTS,
    load_declared_counts,
    run_stats,
)

MANIFEST_NAME = "retrieval_recall_backfill.json"

#: Fields written by this backfill, in export order.
RECALL_FIELDS = [
    "retrieval_assertions_total",
    "retrieval_assertions_evaluated",
    "retrieval_assertions_passed",
    "retrieval_recall",
    "retrieval_recall_ci_low",
    "retrieval_recall_ci_high",
]

#: Fallback column set — mirrors ``BenchmarkRunner._export_results`` for run
#: directories whose ``summary.csv`` is missing. ``tests/test_retrieval_recall.py``
#: asserts this equals a freshly exported header, so the two cannot drift.
DEFAULT_FIELDS = [
    "run_id",
    "scenario_id",
    "model_id",
    "prompt_id",
    "agent_level",
    "memory_backend",
    "embedding_model_id",
    "top_k",
    "chunk_size",
    "chunk_overlap",
    "documents_ingested",
    "ingested_chars",
    "ingested_chunks",
    "corpus_chunks",
    "ingestion_latency_ms",
    "embedding_cache_hits",
    "embedding_cache_misses",
    "total_turns",
    "total_assertions",
    "passed_assertions",
    "failed_assertions",
    "pass_rate",
    "retrieval_assertions_total",
    "retrieval_assertions_evaluated",
    "retrieval_assertions_passed",
    "retrieval_recall",
    "retrieval_recall_ci_low",
    "retrieval_recall_ci_high",
    "error_turns",
    "error_rate",
    "total_latency_ms",
    "avg_latency_per_turn_ms",
    "total_tokens",
    "prompt_tokens",
    "completion_tokens",
    "input_cost_usd",
    "output_cost_usd",
    "total_cost_usd",
    "input_cost_per_mtok",
    "output_cost_per_mtok",
    "timestamp",
]


# ── Core helpers (pure enough to unit-test) ─────────────────────────────────


def recall_payload(run: dict[str, Any], declared_counts: dict[str, int]) -> dict[str, Any]:
    """Return the six recall values for one run summary."""
    stats = run_stats(run, declared_counts)
    recall = None
    if stats["declared"] > 0:
        recall, ci_low, ci_high = recall_with_ci(stats["passed"], stats["declared"])
    else:
        ci_low = ci_high = None
    return {
        "retrieval_assertions_total": stats["declared"],
        "retrieval_assertions_evaluated": stats["evaluated"],
        "retrieval_assertions_passed": stats["passed"],
        "retrieval_recall": recall,
        "retrieval_recall_ci_low": ci_low,
        "retrieval_recall_ci_high": ci_high,
        "_drift": stats["denominator_drift"],
        "_evaluated": stats["evaluated"],
        "_declared": stats["declared"],
    }


def merge_recall(run: dict[str, Any], values: dict[str, Any]) -> dict[str, Any]:
    """Insert the recall fields after ``pass_rate`` (readability of the JSON)."""
    out: dict[str, Any] = {}
    recall_only = {k: v for k, v in values.items() if not k.startswith("_")}
    for key, value in run.items():
        out[key] = value
        if key == "pass_rate":
            out.update(recall_only)
    if not any(k in out for k in recall_only):  # no pass_rate in the record
        out.update(recall_only)
    return out


def csv_fieldnames(existing_header: list[str] | None) -> list[str]:
    """Existing header + the six recall columns after ``pass_rate``."""
    if not existing_header:
        return list(DEFAULT_FIELDS)
    names = [c for c in existing_header if c not in RECALL_FIELDS]
    if "pass_rate" in names:
        idx = names.index("pass_rate") + 1
    else:
        idx = len(names)
    return names[:idx] + RECALL_FIELDS + names[idx:]


def _backup(path: Path) -> None:
    """Create ``<name>.bak`` once; never clobber an earlier backup."""
    backup = path.with_suffix(path.suffix + ".bak")
    if path.exists() and not backup.exists():
        shutil.copy2(path, backup)


def backfill_dir(
    run_dir: Path,
    declared_counts: dict[str, int],
    dry_run: bool = False,
) -> dict[str, Any] | None:
    """Patch one run directory in place. Returns a stats dict, or ``None``."""
    results_path = run_dir / "results.json"
    if not results_path.is_file():
        return None
    try:
        runs = json.loads(results_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(runs, list):
        runs = [runs]

    enriched: list[dict[str, Any]] = []
    info = {
        "runs": 0,
        "runs_with_pins": 0,
        "passed": 0,
        "declared": 0,
        "drift_runs": [],
    }
    for run in runs:
        if not isinstance(run, dict):
            enriched.append(run)
            continue
        values = recall_payload(run, declared_counts)
        enriched.append(merge_recall(run, values))
        info["runs"] += 1
        if values["_declared"] > 0:
            info["runs_with_pins"] += 1
            info["passed"] += values["retrieval_assertions_passed"]
            info["declared"] += values["_declared"]
        if values["_drift"]:
            info["drift_runs"].append(run.get("run_id"))
    info["run_dir"] = run_dir.name
    if info["runs_with_pins"] == 0 and not dry_run:
        return info  # nothing to add; leave the directory untouched

    if dry_run:
        return info

    _backup(results_path)
    results_path.write_text(
        json.dumps(enriched, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    csv_path = run_dir / "summary.csv"
    header: list[str] | None = None
    if csv_path.is_file():
        _backup(csv_path)
        with open(csv_path, encoding="utf-8-sig", newline="") as fh:
            header = next(csv.reader(fh), None)
    fieldnames = csv_fieldnames(header)
    with open(csv_path, "w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for run in enriched:
            if not isinstance(run, dict):
                continue
            writer.writerow({name: run.get(name, "") for name in fieldnames})

    (run_dir / MANIFEST_NAME).write_text(
        json.dumps(
            {
                "backfilled_at": datetime.now(timezone.utc).isoformat(),
                "source": "scripts/backfill_retrieval_recall.py",
                "denominator": "declared must_retrieve_chunk pins (SPEC §5.8 D1)",
                "runs_with_pins": info["runs_with_pins"],
                "passed": info["passed"],
                "declared": info["declared"],
                "drift_run_ids": info["drift_runs"],
                "note": (
                    "Scenarios are read from the current YAML; runs listed in "
                    "drift_run_ids were executed before their scenario gained "
                    "pins, so their recall is a lower bound over today's "
                    "denominator."
                ),
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    return info



# ── CLI ─────────────────────────────────────────────────────────────────────


def iter_run_dirs(root: Path) -> list[Path]:
    """Directory holding ``results.json`` directly, or ``root`` itself."""
    if (root / "results.json").is_file():
        return [root]
    return sorted({path.parent for path in root.rglob("results.json")})


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Add the SPEC §5.8 retrieval-recall fields to runs produced before "
            "the runner exported them."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--results",
        type=Path,
        default=DEFAULT_RESULTS,
        help="Run directory, or root scanned recursively for results.json",
    )
    parser.add_argument(
        "--dataset",
        type=Path,
        default=DEFAULT_DATASET,
        help="Scenario YAML root used to read the declared denominator (D1)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Report what would change without writing anything",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if not args.results.exists():
        print(f"Error: results path {args.results} does not exist.")
        return 2
    if not args.dataset.exists():
        print(f"Error: dataset path {args.dataset} does not exist.")
        return 2

    declared_counts = load_declared_counts(args.dataset)
    dirs = iter_run_dirs(args.results)
    if not dirs:
        print(f"No results.json found under {args.results}.")
        return 1

    touched = 0
    skipped = 0
    total_passed = 0
    total_declared = 0
    drift = 0
    print(f"{'run dir':22s} {'runs':>4s} {'pins':>4s} {'hit':>4s} {'declared':>8s} {'drift':>5s}")
    print("-" * 54)
    for run_dir in dirs:
        info = backfill_dir(run_dir, declared_counts, dry_run=args.dry_run)
        if info is None:
            continue
        if info["runs_with_pins"] == 0:
            skipped += 1
            continue
        touched += 1
        total_passed += info["passed"]
        total_declared += info["declared"]
        drift += len(info["drift_runs"])
        print(
            f"{run_dir.name:22s} {info['runs']:>4d} "
            f"{info['runs_with_pins']:>4d} {info['passed']:>4d} "
            f"{info['declared']:>8d} {len(info['drift_runs']):>5d}"
        )
        if info["drift_runs"]:
            print(f"    drift (lower bound): {', '.join(str(r) for r in info['drift_runs'])}")

    verb = "would patch" if args.dry_run else "patched"
    print("-" * 54)
    print(
        f"{verb} {touched} run dir(s) ({skipped} without retrieval pins left "
        f"untouched) — {total_passed}/{total_declared} pins hit, "
        f"{drift} run(s) with denominator drift."
    )
    if args.dry_run:
        print("Dry run: nothing written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
